// Packs the doll's part SVGs (art/svg/doll/, the editable sources) into ONE
// SVG, assets/art/doll/atlas.svg, plus atlas.json (each part's rectangle in
// SVG pixels). One texture lets Godot batch a doll's sprites into a few draw
// calls instead of one per part -- twelve dolls of separate textures cost
// ~180 draw calls and half the frame rate in a software-rendered browser
// (Step 04 measurement).
//
//   node windup/tools/art/build_doll_atlas.mjs
//
// Ids inside each part (gradients) are prefixed with the part name so they
// cannot collide in the combined file.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, '../../art/svg/doll');
const out = path.resolve(here, '../../assets/art/doll');
const PARTS = ['head', 'torso', 'arm', 'leg', 'back_key', 'eye_closed', 'eye_half', 'eye_open'];
const PAD = 4;

let x = PAD;
let height = 0;
const groups = [];
const rects = {};
for (const name of PARTS) {
  const text = fs.readFileSync(path.join(src, `${name}.svg`), 'utf8');
  const w = Number(text.match(/<svg[^>]*\swidth="([\d.]+)"/)[1]);
  const h = Number(text.match(/<svg[^>]*\sheight="([\d.]+)"/)[1]);
  let inner = text.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  inner = inner.replace(/id="([^"]+)"/g, `id="${name}-$1"`).replace(/url\(#([^)]+)\)/g, `url(#${name}-$1)`);
  groups.push(`  <g transform="translate(${x} ${PAD})">${inner}</g>`);
  rects[name] = [x, PAD, w, h];
  x += w + PAD;
  height = Math.max(height, h);
}
const W = x;
const H = height + PAD * 2;
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'atlas.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">\n` +
  `  <!-- GENERATED by windup/tools/art/build_doll_atlas.mjs from art/svg/doll/*.svg. Edit the sources. -->\n` +
  groups.join('\n') + '\n</svg>\n');
fs.writeFileSync(path.join(out, 'atlas.json'), JSON.stringify({ size: [W, H], parts: rects }, null, 1) + '\n');
console.log(`atlas ${W}x${H}: ${PARTS.length} parts`);
