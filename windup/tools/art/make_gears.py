#!/usr/bin/env python3
"""Writes the two gear SVGs (assets/art/gear_big.svg, gear_small.svg).

    python3 windup/tools/art/make_gears.py

Gear teeth are geometry, so they are computed here rather than drawn by hand:
the big gear behind the key (16 teeth, pitch radius ~88) and the small gear
of the growing gear train (9 teeth, pitch radius ~26). Standard library only.
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'assets', 'art')


def gear(r_root, r_tip, teeth, cx, cy):
    pts = []
    w = 2 * math.pi / teeth
    for i in range(teeth):
        a0 = w * i
        for frac, r in [(0.0, r_root), (0.18, r_tip), (0.5, r_tip), (0.68, r_root)]:
            a = a0 + w * frac
            pts.append(f"{cx + r * math.cos(a):.1f},{cy + r * math.sin(a):.1f}")
    return "M" + " L".join(pts) + " Z"


BIG = f'''<svg xmlns="http://www.w3.org/2000/svg" width="208" height="208" viewBox="0 0 208 208">
  <!-- GENERATED by windup/tools/art/make_gears.py. The big gear behind the key;
       centre (104,104) is the axis, pitch radius ~88. -->
  <defs>
    <radialGradient id="g" cx="0.4" cy="0.35" r="0.75">
      <stop offset="0" stop-color="#8a6230"/>
      <stop offset="1" stop-color="#3d2a17"/>
    </radialGradient>
  </defs>
  <path d="{gear(86, 100, 16, 104, 104)}" fill="url(#g)" stroke="#21160b" stroke-width="3" stroke-linejoin="round"/>
  <circle cx="104" cy="104" r="62" fill="#4a3320" stroke="#21160b" stroke-width="3"/>
  <g fill="#2a1c10">
    <circle cx="104" cy="66" r="10"/><circle cx="142" cy="104" r="10"/><circle cx="104" cy="142" r="10"/><circle cx="66" cy="104" r="10"/>
  </g>
  <circle cx="104" cy="104" r="22" fill="#6e4b22" stroke="#21160b" stroke-width="3"/>
</svg>
'''

SMALL = f'''<svg xmlns="http://www.w3.org/2000/svg" width="76" height="76" viewBox="0 0 76 76">
  <!-- GENERATED by windup/tools/art/make_gears.py. A gear of the growing gear
       train; centre (38,38), pitch radius ~26. -->
  <defs>
    <radialGradient id="g" cx="0.38" cy="0.32" r="0.8">
      <stop offset="0" stop-color="#f0c66a"/>
      <stop offset="0.6" stop-color="#b58232"/>
      <stop offset="1" stop-color="#6e4b22"/>
    </radialGradient>
  </defs>
  <path d="{gear(25, 34, 9, 38, 38)}" fill="url(#g)" stroke="#3a2410" stroke-width="2.4" stroke-linejoin="round"/>
  <circle cx="38" cy="38" r="15" fill="#c9963e" stroke="#3a2410" stroke-width="2"/>
  <circle cx="38" cy="38" r="5" fill="#3a2410"/>
  <path d="M30 30 A 11 11 0 0 1 44 28" fill="none" stroke="#ffe7a3" stroke-width="2" stroke-linecap="round" opacity="0.8"/>
</svg>
'''

if __name__ == '__main__':
    for name, text in [('gear_big.svg', BIG), ('gear_small.svg', SMALL)]:
        with open(os.path.join(OUT, name), 'w') as f:
            f.write(text)
        print('wrote', name)
