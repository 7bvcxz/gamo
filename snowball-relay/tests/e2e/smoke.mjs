import { chromium, open, state, padSwipe, rectCenter, tap, sleep } from './lib.mjs';
import fs from 'node:fs';
const out = process.argv[2] || '/tmp/claude-1000/snow-smoke';
fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const { page, cdp, errors } = await open(browser, { w: 390, h: 844 });
await sleep(800);
await page.screenshot({ path: `${out}/0_fresh.png` });
const s0 = await state(page);
console.log('fresh', JSON.stringify({ snow: s0.snow, speed: s0.speed, view: s0.view }));
await padSwipe(page, cdp, 0.5);
await sleep(600);
await page.screenshot({ path: `${out}/1_rolling.png` });
const s1 = await state(page);
console.log('after swipe +0.6s', JSON.stringify({ snow: s1.snow, speed: s1.speed, dist: s1.dist, pushes: s1.pushes }));
await sleep(3500);
const s2 = await state(page);
console.log('after +4s', JSON.stringify({ snow: s2.snow, speed: s2.speed, dist: s2.dist, lastRoll: s2.lastRoll }));
console.log('errors', errors);
await browser.close();
