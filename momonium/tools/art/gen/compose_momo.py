#!/usr/bin/env python3
"""Step 46: builds assets/src/svg/momo_front.svg (the portrait the UI shows)
from the rig's own parts, stacked in the rig's draw order, so the portrait
and the walking Momo can never drift apart. Gradient ids are prefixed per
part (every part defines its own `fur`, `cloth` ...).

    python3 momonium/tools/art/gen/compose_momo.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[3]
PARTS = ROOT / "assets/src/svg/momo"
OUT = ROOT / "assets/src/svg/momo_front.svg"
# MomoRig.setup: body_root gets legs, body, arms; then the head root with
# head, eyes, tuft and the ears on top.
ORDER = ["leg_l", "leg_r", "body", "arm_l", "arm_r", "head", "eyes_open", "tuft", "ear_l", "ear_r"]


def inner(part: str) -> str:
    text = (PARTS / f"{part}.svg").read_text()
    body = re.sub(r"^<svg[^>]*>", "", text.strip())
    body = re.sub(r"</svg>\s*$", "", body)
    body = re.sub(r"<!--.*?-->", "", body, flags=re.S)
    ids = re.findall(r'id="([^"]+)"', body)
    for i in ids:
        body = body.replace(f'id="{i}"', f'id="{part}_{i}"').replace(f"url(#{i})", f"url(#{part}_{i})")
    return body.strip()


def main() -> None:
    parts = "\n".join(f"<g><!-- {p} -->{inner(p)}</g>" for p in ORDER)
    OUT.write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 220" width="200" height="220">'
        "<!-- Momo, front, standing: generated by tools/art/gen/compose_momo.py from the rig parts "
        "in svg/momo/ (edit those, not this). Origin pivot (feet centre) is (100, 210). -->\n"
        + parts + "\n</svg>\n")
    print("compose_momo:", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
